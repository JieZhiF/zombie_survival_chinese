-- ============================================================
-- 文件: obj_vector_extend.lua
-- 作用: 共享脚本（同时在服务器和客户端运行）
-- 功能: 扩展向量(Vector)对象的元表
--       添加自定义距离计算方法，并重载运算符实现引用操作
-- ============================================================

-- 以下是本文件所有扩展函数和运算符的简要说明：
-- DistanceZSkew —— 计算两个向量的距离，Z 轴应用倾斜/权重因子
-- __pow (^ 运算符) —— 将向量标准化并设置长度（引用操作，直接修改原向量）
-- __mod (% 运算符) —— 将向量的 Z 分量增加指定值（引用操作）
-- __len (# 运算符) —— 返回向量的长度
-- NormalizeRef —— 将向量自身标准化并返回自身引用

-- 获取向量对象的 Lua 元表
local meta = FindMetaTable("Vector")

-- ============================================================
-- 带 Z 轴偏斜的距离计算
-- 计算两个向量之间的距离，但允许对 Z 轴差值应用权重因子
-- 当需要强调或弱化高度差对距离的影响时使用
-- vec: 目标向量
-- skew: Z 轴权重因子（大于 1 放大高度影响，小于 1 缩小）
-- ============================================================
function meta:DistanceZSkew(vec, skew)
	return math.sqrt((self.x - vec.x) ^ 2 + (self.y - vec.y) ^ 2 + ((self.z - vec.z) * skew) ^ 2)
end

-- ============================================================
-- 运算符重载：^（幂运算符）
-- 功能：将向量标准化（长度变为 1），然后将长度设置为指定值
-- 特点：这是引用操作，直接修改原向量而非返回副本
-- len: 目标长度（默认 1）
-- 返回值：修改后的自身引用
-- ============================================================
function meta:__pow(len)
	-- 先将向量标准化为单位向量
	self:Normalize()
	-- 如果长度为 1，直接返回（无需额外计算）
	if len == 1 then
		return self
	end

	-- 将单位向量的每个分量乘以目标长度
	self.x = self.x * len
	self.y = self.y * len
	self.z = self.z * len

	return self
end

-- ============================================================
-- 运算符重载：%（取模运算符）
-- 功能：将向量的 Z 分量增加指定的数值
-- 特点：引用操作，直接修改原向量
-- z: Z 轴的增加值
-- 返回值：修改后的自身引用
-- ============================================================
function meta:__mod(z)
	self.z = self.z + z

	return self
end

-- ============================================================
-- 运算符重载：#（长度运算符）
-- 功能：返回向量的长度（大小）
-- 返回值：向量的长度值
-- ============================================================
function meta:__len()
	return self:Length()
end

-- ============================================================
-- 引用式标准化
-- 将向量自身标准化（长度变为 1）并返回自身的引用
-- 与 GetNormalized() 不同，GetNormalized 会创建并返回一个新的向量副本
-- 而本方法直接修改原向量，节省内存分配
-- 返回值：标准化后的自身引用
-- ============================================================
function meta:NormalizeRef()
	self:Normalize()
	return self
end
