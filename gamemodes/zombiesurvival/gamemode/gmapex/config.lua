-- gmapex/config.lua - 地图扩展(GMAPEX)系统的权限配置
-- 负责：定义地图扩展工具的使用权限，仅允许超级管理员使用
-- ============================================================================

-- ==== GMAPEX:CanUse - 判断玩家是否有权使用地图扩展工具 ====
function GMAPEX:CanUse(pl)
	-- 仅超级管理员（SuperAdmin）可以使用地图扩展功能
	return pl:IsSuperAdmin()
end
