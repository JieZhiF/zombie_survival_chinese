-- 继承基础冲击地雷实体，沿用其感应、引爆与视觉逻辑
ENT.Base = "projectile_impactmine"

-- ==== GetStartPos - 获取激光扫描起点：地雷顶面上方 5 单位 ====
function ENT:GetStartPos()
	return self:GetPos() + self:GetUp() * 5
end
