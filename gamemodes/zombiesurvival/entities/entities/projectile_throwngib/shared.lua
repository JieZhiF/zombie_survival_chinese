-- 动画实体类型（物理投射物）
ENT.Type = "anim"

-- ==== ShouldNotCollide - 碰撞过滤：不碰撞任何僵尸玩家 ====
function ENT:ShouldNotCollide(ent)
	return ent:IsPlayer() and ent:Team() == TEAM_UNDEAD
end
