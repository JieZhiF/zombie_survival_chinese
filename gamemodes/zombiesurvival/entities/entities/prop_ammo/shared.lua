-- shared.lua - 弹药箱道具（共享）：声明实体类型与拾取条件
-- 负责：定义弹药箱不可用钉子加固，仅按住使用键时可被人类拾起
-- ============================================================================
-- 动画实体类型
ENT.Type = "anim"
-- 基类为描边道具基类（提供高亮描边、可被举起等通用逻辑）
ENT.Base = "prop_baseoutlined"

-- 不可用钉子加固（弹药箱为消耗品道具）
ENT.NoNails = true

-- ==== HumanHoldable - 是否可被人类拾起：按住使用键时 ====
function ENT:HumanHoldable(pl)
	return pl:KeyDown(GAMEMODE.UtilityKey)
end
