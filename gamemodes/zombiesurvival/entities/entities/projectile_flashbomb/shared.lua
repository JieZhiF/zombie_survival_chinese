-- 动画实体类型（带物理模拟的投射物）
ENT.Type = "anim"

-- 半透明渲染组（爆炸前发光提示）
ENT.RenderGroup = RENDERGROUP_TRANSLUCENT

-- 飞行寿命（秒），超时后自动爆炸
ENT.LifeTime = 1.5
-- 致盲爆炸的有效半径（单位）
ENT.Radius = 510

-- ==== ShouldNotCollide - 碰撞过滤：玩家不阻挡闪光弹飞行 ====
function ENT:ShouldNotCollide(ent)
	return ent:IsPlayer()
end
