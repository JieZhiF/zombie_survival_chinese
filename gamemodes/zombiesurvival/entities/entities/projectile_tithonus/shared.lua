-- ============================================================================
-- 动画实体类型（具备物理模拟的投射物）
ENT.Type = "anim"

-- ==== ShouldNotCollide - 碰撞过滤：毒针不与其他实体发生物理碰撞 ====
function ENT:ShouldNotCollide(ent)
	-- 穿过所有玩家、其他投射物与僵尸构造物（命中判定改由射线检测完成）
	return ent:IsPlayer() or ent:IsProjectile() or ent.ZombieConstruction
end
