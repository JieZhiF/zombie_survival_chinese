-- 动画实体类型（具备物理模拟的投射物）
ENT.Type = "anim"

-- ==== ShouldNotCollide - 碰撞过滤：石块直接穿过人类玩家 ====
function ENT:ShouldNotCollide(ent)
	return ent:IsPlayer() and ent:Team() == TEAM_HUMAN
end

-- 命中玩家时造成的钝击伤害
ENT.Damage = 100
