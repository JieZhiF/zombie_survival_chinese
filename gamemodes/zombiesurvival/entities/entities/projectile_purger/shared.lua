-- 实体类型：带动画物理的投射物
ENT.Type = "anim"
-- 对净化目标的生命值治疗量
ENT.Heal = 7

-- ==== ShouldNotCollide - 投射物之间互不碰撞，避免误触发 ====
function ENT:ShouldNotCollide(ent)
	return ent:IsProjectile()
end
